#!/usr/bin/env node
import {
  DEFAULT_EXT_PATH,
  DEFAULT_RELAY_HOST,
  DEFAULT_RELAY_PORT,
} from '@agent-browser-bridge/protocol';
import { removeDaemonState, writeDaemonState } from './daemon.js';
import { RelayServer } from './server.js';

function parseArgs(argv: string[]) {
  const out: { host?: string; port?: number; extPath?: string; token?: string } = {};
  for (let i = 0; i < argv.length; i++) {
    const arg = argv[i];
    if ((arg === '--host' || arg === '-h') && argv[i + 1]) {
      out.host = argv[++i];
    } else if ((arg === '--port' || arg === '-p') && argv[i + 1]) {
      out.port = Number(argv[++i]);
    } else if (arg === '--ext-path' && argv[i + 1]) {
      out.extPath = argv[++i];
    } else if ((arg === '--token' || arg === '-t') && argv[i + 1]) {
      out.token = argv[++i];
    }
  }
  return out;
}

async function main() {
  const cli = parseArgs(process.argv.slice(2));
  const host = cli.host ?? process.env.ABB_RELAY_HOST ?? DEFAULT_RELAY_HOST;
  const port = cli.port ?? (process.env.ABB_RELAY_PORT ? Number(process.env.ABB_RELAY_PORT) : DEFAULT_RELAY_PORT);
  const extPath = cli.extPath ?? process.env.ABB_RELAY_EXT_PATH ?? DEFAULT_EXT_PATH;
  const token = cli.token ?? process.env.ABB_RELAY_TOKEN;

  const relay = new RelayServer({ host, port, extPath, token });
  const started = await relay.start();

  await writeDaemonState({
    pid: process.pid,
    host: started.host,
    port: started.port,
    extPath: relay.extPath,
    tokenRequired: relay.tokenRequired,
    cdpWsUrl: started.cdpWsUrl,
    startedAt: Date.now(),
  });

  console.info(`[agent-browser-relay] Listening on http://${started.host}:${started.port}`);
  console.info(`[agent-browser-relay] Extension endpoint: ws://${started.host}:${started.port}${relay.extPath}`);
  console.info(`[agent-browser-relay] Local CDP endpoint: ${started.cdpWsUrl}`);
  if (relay.tokenRequired) {
    if (relay.tokenAutoGenerated && started.token) {
      console.info(`[agent-browser-relay] Remote bind detected — generated required token: ${started.token}`);
    } else {
      console.info('[agent-browser-relay] Token authentication enabled.');
    }
  }

  const shutdown = async () => {
    await relay.stop();
    await removeDaemonState(started.port);
    process.exit(0);
  };

  process.once('SIGINT', () => {
    void shutdown();
  });
  process.once('SIGTERM', () => {
    void shutdown();
  });
}

main().catch((err) => {
  console.error('[agent-browser-relay] Fatal error:', err);
  process.exit(1);
});
