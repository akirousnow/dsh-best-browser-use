import { randomBytes, randomUUID } from 'node:crypto';
import { createServer, type IncomingMessage, type Server, type ServerResponse } from 'node:http';
import type { AddressInfo } from 'node:net';
import type { Duplex } from 'node:stream';
import { WebSocketServer, type WebSocket } from 'ws';
import {
  DEFAULT_EXT_PATH,
  DEFAULT_HEARTBEAT_INTERVAL_MS,
  DEFAULT_HEARTBEAT_TIMEOUT_MS,
  DEFAULT_RELAY_HOST,
  DEFAULT_RELAY_PORT,
  MAX_WS_PAYLOAD_BYTES,
  PROTOCOL_VERSION,
  decodeMessage,
  encodeMessage,
  type ControlCommandMessage,
  type ControlResponseMessage,
  type ExtensionClientInfo,
  type ExtensionTabSummary,
  type RelayStatusSnapshot,
  type RelayToExtensionMessage,
  type TabPolicyMode,
} from '@agent-browser-bridge/protocol';
import {
  extractTokenFromRequest,
  generateSecureToken,
  isLoopbackAddress,
  normalizePath,
  validateCdpOrigin,
  validateExtensionOrigin,
  validateToken,
} from './auth.js';
import { SessionMux } from './session-mux.js';

export interface RelayServerOptions {
  host?: string;
  port?: number;
  extPath?: string;
  token?: string;
  heartbeatIntervalMs?: number;
  heartbeatTimeoutMs?: number;
  commandTimeoutMs?: number;
  maxPayloadBytes?: number;
  logger?: Pick<Console, 'info' | 'warn' | 'error'>;
}

interface PendingControlRequest {
  resolve: (res: ControlResponseMessage) => void;
  reject: (err: Error) => void;
  timer: ReturnType<typeof setTimeout>;
}

/**
 * Permanent CDP Relay Daemon.
 *
 * Security model:
 * - /ext accepts outbound connections from the Chrome MV3 extension.
 *   Enforces CSWSH Origin allowlist (chrome-extension:// or absent Origin).
 *   When bound to a non-loopback interface, enforces a mandatory Token (auto-generated if omitted).
 * - /cdp, /cdp/<secret>, /json/version, /json/list, /status, /control are STRICTLY loopback-only
 *   (remoteAddress must be loopback) and reject browser web Origin headers.
 */
export class RelayServer {
  readonly relayId = randomUUID();
  readonly host: string;
  readonly extPath: string;
  readonly token: string | undefined;
  readonly tokenAutoGenerated: boolean;
  readonly tokenRequired: boolean;
  readonly cdpSecret: string;

  private readonly requestedPort: number;
  private boundPort = 0;
  private readonly heartbeatIntervalMs: number;
  private readonly heartbeatTimeoutMs: number;
  private readonly maxPayloadBytes: number;
  private readonly logger: Pick<Console, 'info' | 'warn' | 'error'>;

  private readonly httpServer: Server;
  private readonly extWss: WebSocketServer;
  private readonly cdpWss: WebSocketServer;
  private readonly mux: SessionMux;

  private extensionSocket: WebSocket | null = null;
  private extensionInfo: ExtensionClientInfo | null = null;
  private tabs: ExtensionTabSummary[] = [];
  private startedAt = 0;
  private heartbeatTimer: ReturnType<typeof setInterval> | null = null;
  private nextControlId = 1;
  private readonly pendingControls = new Map<number, PendingControlRequest>();
  private readonly extensionListeners = new Set<(connected: boolean) => void>();

  constructor(options: RelayServerOptions = {}) {
    this.host = options.host ?? DEFAULT_RELAY_HOST;
    this.requestedPort = options.port ?? DEFAULT_RELAY_PORT;
    this.extPath = normalizePath(options.extPath, DEFAULT_EXT_PATH);
    this.heartbeatIntervalMs = options.heartbeatIntervalMs ?? DEFAULT_HEARTBEAT_INTERVAL_MS;
    this.heartbeatTimeoutMs = options.heartbeatTimeoutMs ?? DEFAULT_HEARTBEAT_TIMEOUT_MS;
    this.maxPayloadBytes = options.maxPayloadBytes ?? MAX_WS_PAYLOAD_BYTES;
    this.logger = options.logger ?? console;
    this.cdpSecret = randomBytes(16).toString('hex');

    const bindingLoopback = isLoopbackAddress(this.host);
    if (!bindingLoopback) {
      if (options.token && options.token.trim().length > 0) {
        this.token = options.token.trim();
        this.tokenAutoGenerated = false;
      } else {
        this.token = generateSecureToken(32);
        this.tokenAutoGenerated = true;
      }
      this.tokenRequired = true;
    } else {
      this.token = options.token && options.token.trim().length > 0 ? options.token.trim() : undefined;
      this.tokenAutoGenerated = false;
      this.tokenRequired = this.token !== undefined;
    }

    this.mux = new SessionMux({
      commandTimeoutMs: options.commandTimeoutMs,
      sendToExtension: (cmd) => this.sendToExtension(cmd),
    });

    this.extWss = new WebSocketServer({
      noServer: true,
      maxPayload: this.maxPayloadBytes,
    });
    this.cdpWss = new WebSocketServer({
      noServer: true,
      maxPayload: this.maxPayloadBytes,
    });

    this.httpServer = createServer((req, res) => {
      void this.handleHttpRequest(req, res);
    });

    this.httpServer.on('upgrade', (req, socket, head) => {
      this.handleUpgrade(req, socket, head);
    });
  }

  get port(): number {
    return this.boundPort || this.requestedPort;
  }

  get cdpWsPath(): string {
    return `/cdp/${this.cdpSecret}`;
  }

  get cdpWsUrl(): string {
    return `ws://127.0.0.1:${this.port}${this.cdpWsPath}`;
  }

  get cdpBaseUrl(): string {
    return `http://127.0.0.1:${this.port}`;
  }

  get isExtensionConnected(): boolean {
    return this.extensionSocket !== null && this.extensionSocket.readyState === this.extensionSocket.OPEN;
  }

  onExtensionStateChange(listener: (connected: boolean) => void): () => void {
    this.extensionListeners.add(listener);
    return () => {
      this.extensionListeners.delete(listener);
    };
  }

  async start(): Promise<{ host: string; port: number; cdpWsUrl: string; token?: string }> {
    if (this.startedAt > 0) {
      return { host: this.host, port: this.port, cdpWsUrl: this.cdpWsUrl, token: this.token };
    }

    await new Promise<void>((resolve, reject) => {
      const onError = (err: Error) => {
        this.httpServer.off('listening', onListening);
        reject(err);
      };
      const onListening = () => {
        this.httpServer.off('error', onError);
        const addr = this.httpServer.address() as AddressInfo | null;
        this.boundPort = addr?.port ?? this.requestedPort;
        this.startedAt = Date.now();
        resolve();
      };
      this.httpServer.once('error', onError);
      this.httpServer.once('listening', onListening);
      this.httpServer.listen(this.requestedPort, this.host);
    });

    const sweepEveryMs = Math.max(1_000, Math.min(this.heartbeatIntervalMs, 10_000));
    this.heartbeatTimer = setInterval(() => {
      this.checkExtensionHeartbeat();
    }, sweepEveryMs);
    this.heartbeatTimer.unref?.();

    return { host: this.host, port: this.port, cdpWsUrl: this.cdpWsUrl, token: this.token };
  }

  async stop(): Promise<void> {
    if (this.heartbeatTimer) {
      clearInterval(this.heartbeatTimer);
      this.heartbeatTimer = null;
    }

    for (const [id, ctrl] of this.pendingControls.entries()) {
      clearTimeout(ctrl.timer);
      ctrl.reject(new Error('Relay stopping'));
      this.pendingControls.delete(id);
    }

    this.mux.closeAll(1001, 'Relay shutting down');

    if (this.extensionSocket) {
      try {
        this.extensionSocket.close(1001, 'Relay shutting down');
      } catch {
        // Ignore.
      }
      this.extensionSocket = null;
      this.extensionInfo = null;
      this.tabs = [];
    }

    await new Promise<void>((resolve) => {
      this.extWss.close(() => {
        this.cdpWss.close(() => {
          if (this.httpServer.listening) {
            this.httpServer.close(() => resolve());
            this.httpServer.closeAllConnections?.();
          } else {
            resolve();
          }
        });
      });
    });

    this.startedAt = 0;
  }

  getStatus(): RelayStatusSnapshot {
    return {
      ok: true,
      relayId: this.relayId,
      protocolVersion: PROTOCOL_VERSION,
      host: this.host,
      port: this.port,
      extPath: this.extPath,
      tokenRequired: this.tokenRequired,
      uptimeMs: this.startedAt > 0 ? Date.now() - this.startedAt : 0,
      extensionConnected: this.isExtensionConnected,
      extension: this.extensionInfo ? { ...this.extensionInfo } : null,
      tabs: this.tabs.map((t) => ({ ...t })),
      cdpClients: this.mux.clientCount,
      cdpWsPath: this.cdpWsPath,
      cdpWsUrl: this.cdpWsUrl,
    };
  }

  /** Send a control action (detach_tab, attach_tab, set_mode, refresh_tabs) to the extension. */
  async sendControl(
    action: ControlCommandMessage['action'],
    opts: { tabId?: number; mode?: TabPolicyMode; timeoutMs?: number } = {},
  ): Promise<ControlResponseMessage> {
    if (!this.isExtensionConnected) {
      throw new Error('Browser extension is not connected');
    }
    const id = this.nextControlId++;
    const cmd: ControlCommandMessage = {
      type: 'control.cmd',
      id,
      action,
      ...(opts.tabId !== undefined ? { tabId: opts.tabId } : {}),
      ...(opts.mode !== undefined ? { mode: opts.mode } : {}),
    };

    return await new Promise<ControlResponseMessage>((resolve, reject) => {
      const timer = setTimeout(() => {
        this.pendingControls.delete(id);
        reject(new Error(`Control action "${action}" timed out`));
      }, opts.timeoutMs ?? 10_000);

      this.pendingControls.set(id, { resolve, reject, timer });
      if (!this.sendToExtension(cmd)) {
        clearTimeout(timer);
        this.pendingControls.delete(id);
        reject(new Error('Failed to send control command to extension'));
      }
    });
  }

  private sendToExtension(msg: RelayToExtensionMessage): boolean {
    if (!this.extensionSocket || this.extensionSocket.readyState !== this.extensionSocket.OPEN) {
      return false;
    }
    try {
      this.extensionSocket.send(encodeMessage(msg));
      return true;
    } catch {
      return false;
    }
  }

  private checkExtensionHeartbeat(): void {
    if (!this.extensionSocket || !this.extensionInfo) return;
    const silentMs = Date.now() - this.extensionInfo.lastHeartbeatAt;
    if (silentMs > this.heartbeatTimeoutMs) {
      this.logger.warn(
        `[relay] Extension heartbeat timed out after ${silentMs}ms; closing stale socket`,
      );
      try {
        this.extensionSocket.terminate();
      } catch {
        // Ignore.
      }
      return;
    }
    if (silentMs >= this.heartbeatIntervalMs) {
      this.sendToExtension({ type: 'ping', ts: Date.now() });
    }
  }

  private handleUpgrade(req: IncomingMessage, socket: Duplex, head: Buffer): void {
    let pathname = '/';
    try {
      pathname = new URL(req.url ?? '/', 'http://127.0.0.1').pathname;
    } catch {
      this.rejectUpgrade(socket, 400, 'Bad Request');
      return;
    }

    if (pathname === this.extPath) {
      const originCheck = validateExtensionOrigin(req.headers.origin);
      if (!originCheck.allowed) {
        this.logger.warn(`[relay] Rejected /ext upgrade: ${originCheck.reason}`);
        this.rejectUpgrade(socket, 403, originCheck.reason ?? 'Forbidden Origin');
        return;
      }

      const providedToken = extractTokenFromRequest(req);
      if (!validateToken(this.token, providedToken)) {
        this.logger.warn('[relay] Rejected /ext upgrade: invalid or missing token');
        this.rejectUpgrade(socket, 401, 'Unauthorized: invalid or missing bridge token');
        return;
      }

      this.extWss.handleUpgrade(req, socket, head, (ws) => {
        this.acceptExtensionConnection(ws, req);
      });
      return;
    }

    const isCdpPath = pathname === '/cdp' || pathname === this.cdpWsPath;
    if (isCdpPath) {
      if (!isLoopbackAddress(req.socket.remoteAddress)) {
        this.logger.warn(
          `[relay] Blocked non-loopback /cdp attempt from ${req.socket.remoteAddress ?? 'unknown'}`,
        );
        this.rejectUpgrade(socket, 403, 'Forbidden: /cdp is restricted to loopback (127.0.0.1)');
        return;
      }

      const originCheck = validateCdpOrigin(req.headers.origin);
      if (!originCheck.allowed) {
        this.logger.warn(`[relay] Rejected /cdp upgrade: ${originCheck.reason}`);
        this.rejectUpgrade(socket, 403, originCheck.reason ?? 'Forbidden Origin');
        return;
      }

      // When Relay is bound to a non-loopback host, require the secret path or valid token on /cdp
      if (!isLoopbackAddress(this.host) && pathname === '/cdp') {
        const providedToken = extractTokenFromRequest(req);
        if (!validateToken(this.token, providedToken)) {
          this.rejectUpgrade(
            socket,
            403,
            'Forbidden: use the secret /cdp/<secret> URL from /status or provide token',
          );
          return;
        }
      }

      this.cdpWss.handleUpgrade(req, socket, head, (ws) => {
        this.mux.addClient(ws);
      });
      return;
    }

    this.rejectUpgrade(socket, 404, 'Not Found');
  }

  private acceptExtensionConnection(ws: WebSocket, req: IncomingMessage): void {
    const previous = this.extensionSocket;
    if (previous && previous !== ws) {
      try {
        previous.close(4000, 'Replaced by newer extension connection');
      } catch {
        // Ignore.
      }
    }

    const remoteAddress = req.socket.remoteAddress;
    const now = Date.now();
    this.extensionSocket = ws;
    this.extensionInfo = {
      extensionVersion: 'unknown',
      browserName: 'Chrome',
      userAgent: typeof req.headers['user-agent'] === 'string' ? req.headers['user-agent'] : '',
      tabPolicyMode: 'auto',
      remoteAddress,
      isRemote: !isLoopbackAddress(remoteAddress),
      connectedAt: now,
      lastHeartbeatAt: now,
    };

    ws.on('message', (data) => {
      if (this.extensionSocket !== ws) return;
      if (this.extensionInfo) {
        this.extensionInfo.lastHeartbeatAt = Date.now();
      }
      const msg = decodeMessage(data.toString('utf8'));
      if (!msg) return;

      switch (msg.type) {
        case 'hello': {
          this.extensionInfo = {
            extensionVersion: msg.extensionVersion,
            browserName: msg.browserName,
            userAgent: msg.userAgent,
            tabPolicyMode: msg.tabPolicyMode,
            remoteAddress,
            isRemote: !isLoopbackAddress(remoteAddress),
            connectedAt: this.extensionInfo?.connectedAt ?? Date.now(),
            lastHeartbeatAt: Date.now(),
          };
          this.tabs = msg.tabs;
          this.sendToExtension({
            type: 'hello.ack',
            protocolVersion: PROTOCOL_VERSION,
            relayId: this.relayId,
            serverTime: Date.now(),
            heartbeatIntervalMs: this.heartbeatIntervalMs,
          });
          this.notifyExtensionListeners(true);
          break;
        }
        case 'ping': {
          this.sendToExtension({ type: 'pong', ts: msg.ts });
          break;
        }
        case 'pong': {
          // Heartbeat timestamp already updated above.
          break;
        }
        case 'tabs.sync': {
          if (this.extensionInfo) {
            this.extensionInfo.tabPolicyMode = msg.mode;
          }
          this.tabs = msg.tabs;
          break;
        }
        case 'cdp.res': {
          this.mux.handleExtensionResponse(msg);
          break;
        }
        case 'cdp.evt': {
          this.mux.broadcastExtensionEvent(msg);
          break;
        }
        case 'control.res': {
          const pending = this.pendingControls.get(msg.id);
          if (pending) {
            clearTimeout(pending.timer);
            this.pendingControls.delete(msg.id);
            if (msg.tabs) this.tabs = msg.tabs;
            if (msg.mode && this.extensionInfo) {
              this.extensionInfo.tabPolicyMode = msg.mode;
            }
            pending.resolve(msg);
          }
          break;
        }
        default:
          break;
      }
    });

    const handleDisconnect = () => {
      if (this.extensionSocket !== ws) return;
      this.extensionSocket = null;
      this.extensionInfo = null;
      this.tabs = [];
      this.mux.failAllPending('Browser extension disconnected');
      for (const [id, ctrl] of this.pendingControls.entries()) {
        clearTimeout(ctrl.timer);
        ctrl.reject(new Error('Browser extension disconnected'));
        this.pendingControls.delete(id);
      }
      this.notifyExtensionListeners(false);
    };

    ws.on('close', handleDisconnect);
    ws.on('error', handleDisconnect);
  }

  private notifyExtensionListeners(connected: boolean): void {
    for (const fn of this.extensionListeners) {
      try {
        fn(connected);
      } catch {
        // Ignore listener errors.
      }
    }
  }

  private async handleHttpRequest(req: IncomingMessage, res: ServerResponse): Promise<void> {
    if (!isLoopbackAddress(req.socket.remoteAddress)) {
      this.sendHttpJson(res, 403, { error: 'Forbidden: HTTP endpoints are loopback-only' });
      return;
    }

    let pathname = '/';
    try {
      pathname = new URL(req.url ?? '/', 'http://127.0.0.1').pathname;
    } catch {
      this.sendHttpJson(res, 400, { error: 'Bad Request' });
      return;
    }

    if (req.method === 'GET' && (pathname === '/status' || pathname === '/health')) {
      this.sendHttpJson(res, 200, this.getStatus());
      return;
    }

    // Standard Chrome DevTools discovery endpoints so playwright-core connectOverCDP("http://127.0.0.1:9229") works!
    if (req.method === 'GET' && pathname === '/json/version') {
      const ua = this.extensionInfo?.userAgent || 'Mozilla/5.0 Chrome/131.0.0.0';
      this.sendHttpJson(res, 200, {
        Browser: `${this.extensionInfo?.browserName ?? 'Chrome'}/AgentBrowserBridge`,
        'Protocol-Version': '1.3',
        'User-Agent': ua,
        'V8-Version': '13.1',
        'WebKit-Version': '537.36',
        webSocketDebuggerUrl: this.cdpWsUrl,
      });
      return;
    }

    if (req.method === 'GET' && (pathname === '/json/list' || pathname === '/json')) {
      const list = this.tabs
        .filter((t) => t.eligible && t.authorized)
        .map((t) => ({
          id: t.targetId,
          type: 'page',
          title: t.title,
          url: t.url,
          webSocketDebuggerUrl: this.cdpWsUrl,
        }));
      this.sendHttpJson(res, 200, list);
      return;
    }

    if (req.method === 'POST' && pathname === '/control') {
      try {
        const body = await this.readJsonBody(req);
        const action = body.action as ControlCommandMessage['action'];
        if (!['detach_tab', 'attach_tab', 'set_mode', 'refresh_tabs'].includes(action)) {
          this.sendHttpJson(res, 400, { error: `Unknown control action: ${String(action)}` });
          return;
        }
        const result = await this.sendControl(action, {
          tabId: typeof body.tabId === 'number' ? body.tabId : undefined,
          mode: body.mode === 'auto' || body.mode === 'manual' ? body.mode : undefined,
        });
        this.sendHttpJson(res, 200, result);
      } catch (err) {
        this.sendHttpJson(res, 502, {
          ok: false,
          error: err instanceof Error ? err.message : String(err),
        });
      }
      return;
    }

    this.sendHttpJson(res, 404, { error: 'Not Found' });
  }

  private async readJsonBody(req: IncomingMessage): Promise<Record<string, unknown>> {
    const chunks: Buffer[] = [];
    let size = 0;
    for await (const chunk of req) {
      const buf = Buffer.isBuffer(chunk) ? chunk : Buffer.from(chunk);
      size += buf.length;
      if (size > 64 * 1024) throw new Error('Request body too large');
      chunks.push(buf);
    }
    const text = Buffer.concat(chunks).toString('utf8').trim();
    if (!text) return {};
    const parsed = JSON.parse(text);
    if (typeof parsed !== 'object' || parsed === null || Array.isArray(parsed)) {
      throw new Error('Request body must be a JSON object');
    }
    return parsed as Record<string, unknown>;
  }

  private sendHttpJson(res: ServerResponse, status: number, body: unknown): void {
    const payload = JSON.stringify(body);
    res.writeHead(status, {
      'content-type': 'application/json; charset=utf-8',
      'cache-control': 'no-store',
    });
    res.end(payload);
  }

  private rejectUpgrade(socket: Duplex, status: number, message: string): void {
    const statusText =
      status === 401 ? 'Unauthorized' : status === 403 ? 'Forbidden' : status === 404 ? 'Not Found' : 'Bad Request';
    const body = `${message}\n`;
    socket.write(
      `HTTP/1.1 ${status} ${statusText}\r\n` +
        'Content-Type: text/plain; charset=utf-8\r\n' +
        `Content-Length: ${Buffer.byteLength(body)}\r\n` +
        'Connection: close\r\n\r\n' +
        body,
    );
    socket.destroy();
  }
}
