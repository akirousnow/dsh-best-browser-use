import { afterEach, describe, expect, it } from 'vitest';
import WebSocket from 'ws';
import { RelayServer, validateExtensionOrigin, isLoopbackAddress } from '../packages/relay/src/index.js';
import { MockExtensionClient } from './mock-extension.js';

function openRawWs(url: string, headers?: Record<string, string>, protocols?: string[]): Promise<WebSocket> {
  return new Promise((resolve, reject) => {
    const ws = new WebSocket(url, protocols, { headers, maxPayload: 64 * 1024 * 1024 });
    ws.once('open', () => resolve(ws));
    ws.once('error', reject);
    ws.once('unexpected-response', (_req, res) => {
      reject(new Error(`HTTP ${res.statusCode}`));
    });
  });
}

function sendCdp(
  ws: WebSocket,
  req: { id: number; method: string; params?: Record<string, unknown>; sessionId?: string },
): Promise<Record<string, unknown>> {
  return new Promise((resolve, reject) => {
    const onMsg = (raw: WebSocket.RawData) => {
      const msg = JSON.parse(raw.toString('utf8')) as Record<string, unknown>;
      if (msg.id === req.id) {
        ws.off('message', onMsg);
        resolve(msg);
      }
    };
    ws.on('message', onMsg);
    ws.once('error', reject);
    ws.send(JSON.stringify(req));
  });
}

async function waitFor(predicate: () => boolean, timeoutMs = 3_000): Promise<void> {
  const deadline = Date.now() + timeoutMs;
  while (Date.now() < deadline) {
    if (predicate()) return;
    await new Promise((resolve) => setTimeout(resolve, 25));
  }
  throw new Error('waitFor timed out');
}

describe('RelayServer security, multiplexing, reconnect & large payloads', () => {
  const servers: RelayServer[] = [];
  const extensions: MockExtensionClient[] = [];
  const sockets: WebSocket[] = [];

  afterEach(async () => {
    for (const s of sockets.splice(0)) {
      if (s.readyState !== WebSocket.CLOSED) s.close();
    }
    for (const ext of extensions.splice(0)) {
      await ext.close();
    }
    for (const srv of servers.splice(0)) {
      await srv.stop();
    }
  });

  it('blocks web page Origins (CSWSH) and accepts chrome-extension:// Origins', async () => {
    expect(validateExtensionOrigin('https://evil.example.com').allowed).toBe(false);
    expect(validateExtensionOrigin('http://127.0.0.1:8080').allowed).toBe(false);
    expect(validateExtensionOrigin('null').allowed).toBe(false);
    expect(validateExtensionOrigin('chrome-extension://abcdefghijklmnop').allowed).toBe(true);
    expect(validateExtensionOrigin(undefined).allowed).toBe(true);

    expect(isLoopbackAddress('127.0.0.1')).toBe(true);
    expect(isLoopbackAddress('::ffff:127.0.0.1')).toBe(true);
    expect(isLoopbackAddress('::1')).toBe(true);
    expect(isLoopbackAddress('0.0.0.0')).toBe(false);
    expect(isLoopbackAddress('192.168.1.5')).toBe(false);

    const relay = new RelayServer({ host: '127.0.0.1', port: 0, logger: { info() {}, warn() {}, error() {} } });
    servers.push(relay);
    const { port } = await relay.start();

    await expect(
      openRawWs(`ws://127.0.0.1:${port}/ext`, { Origin: 'https://evil.example.com' }),
    ).rejects.toThrow('HTTP 403');

    await expect(
      openRawWs(`ws://127.0.0.1:${port}/cdp`, { Origin: 'https://evil.example.com' }),
    ).rejects.toThrow('HTTP 403');

    const ext = new MockExtensionClient({
      wsUrl: `ws://127.0.0.1:${port}/ext`,
      origin: 'chrome-extension://abcdefghijklmnop',
    });
    extensions.push(ext);
    await ext.connect();
    expect(relay.isExtensionConnected).toBe(true);
  });

  it('enforces token authentication and auto-generates mandatory token on non-loopback binds', async () => {
    const relay = new RelayServer({
      host: '127.0.0.1',
      port: 0,
      token: 'super-secret-token',
      logger: { info() {}, warn() {}, error() {} },
    });
    servers.push(relay);
    const { port } = await relay.start();

    // Missing token -> 401
    await expect(openRawWs(`ws://127.0.0.1:${port}/ext`)).rejects.toThrow('HTTP 401');
    // Wrong token -> 401
    await expect(openRawWs(`ws://127.0.0.1:${port}/ext?token=wrong`)).rejects.toThrow('HTTP 401');

    // Query token (used by MV3 WebSocket) -> succeeds
    const ext = new MockExtensionClient({
      wsUrl: `ws://127.0.0.1:${port}/ext?token=super-secret-token`,
      origin: 'chrome-extension://abcdefghijklmnop',
    });
    extensions.push(ext);
    await ext.connect();
    expect(relay.isExtensionConnected).toBe(true);

    // Non-loopback bind forces auto-generated token
    const remoteRelay = new RelayServer({
      host: '0.0.0.0',
      port: 0,
      logger: { info() {}, warn() {}, error() {} },
    });
    servers.push(remoteRelay);
    expect(remoteRelay.tokenRequired).toBe(true);
    expect(remoteRelay.tokenAutoGenerated).toBe(true);
    expect(remoteRelay.token?.length).toBe(64);
  });

  it('multiplexes concurrent CDP clients, passes large (>4 MiB) payloads, and recovers after reconnect', async () => {
    const relay = new RelayServer({ host: '127.0.0.1', port: 0, logger: { info() {}, warn() {}, error() {} } });
    servers.push(relay);
    const { port, cdpWsUrl } = await relay.start();

    const ext = new MockExtensionClient({
      wsUrl: `ws://127.0.0.1:${port}/ext`,
      origin: 'chrome-extension://abcdefghijklmnop',
    });
    extensions.push(ext);
    await ext.connect();

    // Verify /status and /json/version endpoints
    const statusRes = await fetch(`http://127.0.0.1:${port}/status`);
    expect(statusRes.status).toBe(200);
    const statusJson = (await statusRes.json()) as { extensionConnected: boolean; cdpWsUrl: string; tabs: unknown[] };
    expect(statusJson.extensionConnected).toBe(true);
    expect(statusJson.cdpWsUrl).toBe(cdpWsUrl);

    const verRes = await fetch(`http://127.0.0.1:${port}/json/version`);
    const verJson = (await verRes.json()) as { webSocketDebuggerUrl: string };
    expect(verJson.webSocketDebuggerUrl).toBe(cdpWsUrl);

    // Two concurrent CDP clients using identical client request IDs (id: 1)
    const cdp1 = await openRawWs(cdpWsUrl);
    const cdp2 = await openRawWs(cdpWsUrl);
    sockets.push(cdp1, cdp2);

    const [r1, r2] = await Promise.all([
      sendCdp(cdp1, { id: 1, method: 'Browser.getVersion' }),
      sendCdp(cdp2, { id: 1, method: 'Target.getTargets' }),
    ]);

    expect((r1.result as { protocolVersion: string }).protocolVersion).toBe('1.3');
    const targets = (r2.result as { targetInfos: Array<{ url: string }> }).targetInfos;
    // Privileged chrome://settings tab must be filtered out
    expect(targets.map((t) => t.url)).toEqual(['https://example.com/']);

    // Attach to tab 1 and test a 5 MiB payload passthrough
    const attachRes = await sendCdp(cdp1, {
      id: 2,
      method: 'Target.attachToTarget',
      params: { targetId: 'tab-1', flatten: true },
    });
    const sessionId = (attachRes.result as { sessionId: string }).sessionId;
    expect(sessionId).toBeTruthy();

    const bigPayload = 'A'.repeat(5 * 1024 * 1024);
    ext.chromeState.commandHandler = async (_target, method) => {
      if (method === 'Page.captureScreenshot') {
        return { data: bigPayload };
      }
      return { ok: true };
    };

    const bigRes = await sendCdp(cdp1, {
      id: 3,
      method: 'Page.captureScreenshot',
      sessionId,
    });
    expect((bigRes.result as { data: string }).data.length).toBe(5 * 1024 * 1024);

    // Browser.close from cdp1 while cdp2 is still connected must NOT detach tabs
    const closeRes = await sendCdp(cdp1, { id: 4, method: 'Browser.close' });
    expect(closeRes.result).toEqual({});
    expect(ext.chromeState.attachedTabIds.has(1)).toBe(true);

    // Control endpoint detaches tab cleanly
    const ctrlRes = await fetch(`http://127.0.0.1:${port}/control`, {
      method: 'POST',
      headers: { 'content-type': 'application/json' },
      body: JSON.stringify({ action: 'detach_tab', tabId: 1 }),
    });
    const ctrlJson = (await ctrlRes.json()) as { ok: boolean };
    expect(ctrlJson.ok).toBe(true);
    expect(ext.chromeState.attachedTabIds.has(1)).toBe(false);

    // Extension disconnects -> in-flight/new CDP commands get clean error -> reconnect recovers
    await ext.close();
    const errRes = await sendCdp(cdp2, { id: 5, method: 'Browser.getVersion' });
    expect(errRes.error).toBeDefined();

    const ext2 = new MockExtensionClient({
      wsUrl: `ws://127.0.0.1:${port}/ext`,
      origin: 'chrome-extension://abcdefghijklmnop',
    });
    extensions.push(ext2);
    await ext2.connect();

    const recovered = await sendCdp(cdp2, { id: 6, method: 'Browser.getVersion' });
    expect((recovered.result as { protocolVersion: string }).protocolVersion).toBe('1.3');
  });

  it('releases the debugger attachment when the last CDP client disconnects', async () => {
    const relay = new RelayServer({ host: '127.0.0.1', port: 0, logger: { info() {}, warn() {}, error() {} } });
    servers.push(relay);
    const { port, cdpWsUrl } = await relay.start();

    const ext = new MockExtensionClient({
      wsUrl: `ws://127.0.0.1:${port}/ext`,
      origin: 'chrome-extension://abcdefghijklmnop',
    });
    extensions.push(ext);
    await ext.connect();

    const cdp = await openRawWs(cdpWsUrl);
    sockets.push(cdp);

    const attachRes = await sendCdp(cdp, {
      id: 1,
      method: 'Target.attachToTarget',
      params: { targetId: 'tab-1', flatten: true },
    });
    expect((attachRes.result as { sessionId: string }).sessionId).toBeTruthy();
    expect(ext.chromeState.attachedTabIds.has(1)).toBe(true);

    cdp.close();
    await waitFor(() => !ext.chromeState.attachedTabIds.has(1));
    expect(ext.chromeState.attachedTabIds.has(1)).toBe(false);
  });

  it('closes silent extension sockets after heartbeatTimeoutMs', async () => {
    const relay = new RelayServer({
      host: '127.0.0.1',
      port: 0,
      heartbeatIntervalMs: 100,
      heartbeatTimeoutMs: 250,
      logger: { info() {}, warn() {}, error() {} },
    });
    servers.push(relay);
    const { port } = await relay.start();

    const ext = new MockExtensionClient({
      wsUrl: `ws://127.0.0.1:${port}/ext`,
      origin: 'chrome-extension://abcdefghijklmnop',
      autoPong: false,
    });
    extensions.push(ext);
    await ext.connect();
    expect(relay.isExtensionConnected).toBe(true);

    await new Promise((r) => setTimeout(r, 1300));
    expect(relay.isExtensionConnected).toBe(false);
  });
});
